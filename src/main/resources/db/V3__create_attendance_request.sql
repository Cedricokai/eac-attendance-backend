CREATE TABLE IF NOT EXISTS attendance_request (
    id BIGINT NOT NULL AUTO_INCREMENT,
    employee_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    check_in TIME NOT NULL,
    check_out TIME NOT NULL,
    shift VARCHAR(40) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    evidence_reference VARCHAR(255) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    requested_by_user_id BIGINT NOT NULL,
    requested_at DATETIME(6) NOT NULL,
    reviewed_by_user_id BIGINT NULL,
    reviewed_at DATETIME(6) NULL,
    rejection_reason VARCHAR(1000) NULL,
    attendance_id BIGINT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version INT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_attendance_request_attendance (attendance_id),
    KEY idx_attendance_request_status (status),
    KEY idx_attendance_request_employee_date (employee_id, attendance_date),
    CONSTRAINT fk_attendance_request_employee FOREIGN KEY (employee_id) REFERENCES employee (id),
    CONSTRAINT fk_attendance_request_requested_by FOREIGN KEY (requested_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_attendance_request_reviewed_by FOREIGN KEY (reviewed_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_attendance_request_attendance FOREIGN KEY (attendance_id) REFERENCES attendance (id)
);
